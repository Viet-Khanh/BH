// Product code helpers: initials codes ("Coca-Cola lon 320ml" → "CL3") and their
// de-duplication. Sequential codes (SP000001…) come from the API.
export const buildCodeFromName = (name = '') => {
  const cleaned = name.normalize('NFD').replace(/[̀-ͯ]/g, '').trim();
  if (!cleaned) return '';
  return cleaned
    .split(/\s+/)
    .filter(Boolean)
    .map((word) => word[0]?.toUpperCase())
    .join('');
};

const toKey = (code) =>
  String(code ?? '')
    .trim()
    .toLowerCase();

const toKeySet = (codes = []) => new Set([...codes].map(toKey).filter(Boolean));

// "CL3" → "CL3-2", "CL3-3"… when taken (case-insensitive); unchanged when free.
export const dedupeInitialsCode = (code, existingCodes = []) => {
  const keys = toKeySet(existingCodes);
  if (!code || !keys.has(toKey(code))) return code;
  let index = 2;
  while (keys.has(toKey(`${code}-${index}`))) index += 1;
  return `${code}-${index}`;
};

// Code to save: initials generated by the form are de-duplicated against loaded
// products; codes typed by the user or given by the sequence are kept.
export const resolveProductCode = ({
  code,
  name,
  codeEdited = false,
  sequential = false,
  existingCodes = [],
}) => {
  const trimmed = String(code ?? '').trim();
  if (codeEdited || sequential) return trimmed;
  return dedupeInitialsCode(
    trimmed || buildCodeFromName(name || ''),
    existingCodes
  );
};

// Excel import: rows without a code get de-duplicated initials.
export const fillImportCodes = (items = [], existingCodes = []) => {
  const taken = [...existingCodes, ...items.map((item) => item.code)];
  return items.map((item) => {
    if (String(item.code ?? '').trim()) return item;
    const code = dedupeInitialsCode(buildCodeFromName(item.name || ''), taken);
    taken.push(code);
    return { ...item, code };
  });
};
